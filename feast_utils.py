def _load_repo_module(module_name, file_path, repo_path):
    """Load one of the generated Feast repo definition files (entities.py,
    feature_views.py, feature_service.py) as an importable Python module, with
    repo_path temporarily on sys.path so their internal `from entities import ...` /
    `from feature_views import ...` statements resolve correctly - the same way
    Feast's own repo scanner would see them, just done directly instead of via the CLI."""
    import importlib.util
    added_path = repo_path not in sys.path
    if added_path:
        sys.path.insert(0, repo_path)
    try:
        spec = importlib.util.spec_from_file_location(module_name, file_path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[module_name] = module  # so a later `from entities import X` finds it
        spec.loader.exec_module(module)
        return module
    finally:
        if added_path and repo_path in sys.path:
            sys.path.remove(repo_path)


def apply_feast_definitions(repo_path=FEAST_REPO_PATH):
    """Registers/updates the Entity, FeatureView, and FeatureService definitions (from
    entities.py, feature_views.py, feature_service.py) into Feast's registry
    (registry.db) and provisions the online store (online_store.db) schema - the SDK
    equivalent of `feast apply`, run in-process via fs.apply()."""
    from feast import FeatureStore

    for required in ["entities.py", "feature_views.py", "feature_service.py", "feature_store.yaml"]:
        if not os.path.exists(os.path.join(repo_path, required)):
            raise FeastConfigError(
                f"{required} not found in {repo_path}. Run write_offline_source() + "
                f"generate_feature_views_file() + generate_feature_service_file() first."
            )

    try:
        entities_mod = _load_repo_module("entities", os.path.join(repo_path, "entities.py"), repo_path)
        feature_views_mod = _load_repo_module("feature_views", os.path.join(repo_path, "feature_views.py"), repo_path)
        feature_service_mod = _load_repo_module("feature_service", os.path.join(repo_path, "feature_service.py"), repo_path)

        fs = FeatureStore(repo_path=repo_path)
        objects = [
            entities_mod.karachi_location,
            feature_views_mod.karachi_aqi_features,
            getattr(feature_service_mod, FEATURE_SERVICE_NAME),
        ]
        fs.apply(objects)
    except FeastConfigError:
        raise
    except Exception as e:
        raise FeastConfigError(
            f"Feast apply failed ({e}). Check feature_store/feature_store.yaml and the "
            f"generated entities.py / feature_views.py / feature_service.py for errors."
        )

    print(f"Feast apply succeeded (via SDK, repo_path={repo_path}) - "
          f"Entity, FeatureView '{FEATURE_VIEW_NAME}', and FeatureService '{FEATURE_SERVICE_NAME}' are registered.")
    return fs


def materialize_feast_features(start_date, end_date, repo_path=FEAST_REPO_PATH):
    """Makes historical features available in the ONLINE store (SQLite here) for fast
    key-value lookup - copies the point-in-time-correct latest value per entity, for
    feature rows whose event_timestamp falls in [start_date, end_date], out of the
    offline Parquet source and into online_store.db. SDK equivalent of
    `feast materialize <start> <end>`, run in-process via fs.materialize()."""
    from feast import FeatureStore

    start_ts = pd.Timestamp(start_date)
    start_ts = start_ts.tz_convert("UTC") if start_ts.tzinfo else start_ts.tz_localize("UTC")
    end_ts = pd.Timestamp(end_date)
    end_ts = end_ts.tz_convert("UTC") if end_ts.tzinfo else end_ts.tz_localize("UTC")

    fs = FeatureStore(repo_path=repo_path)
    try:
        fs.materialize(start_ts.to_pydatetime(), end_ts.to_pydatetime())
    except Exception as e:
        if "no such table" in str(e):
            raise FeastConfigError(
                f"Feast materialize failed because the online store has no table for this "
                f"FeatureView yet ({e}). Table creation happens during apply, not materialize - "
                f"run apply_feast_definitions() first (it's safe to re-run), then materialize again."
            )
        if "does not exist in project" in str(e):
            raise FeastConfigError(
                f"Feast materialize failed because the registry at {repo_path} doesn't currently "
                f"contain the expected entity/FeatureView/FeatureService ({e}). The registry was "
                f"likely reset or overwritten since it was last applied (a concurrent process re-"
                f"running apply() against the same repo_path, a git pull, a sync tool restoring an "
                f"older version, or multiple project copies on disk being run interchangeably). "
                f"Fix: run apply_feast_definitions() again, then retry materialize."
            )
        raise FeastConfigError(f"Feast materialize failed ({e}).")

    print(f"Materialized (via SDK) features from {start_ts} to {end_ts} into the online store.")
    return fs


def materialize_incremental(end_date=None, repo_path=FEAST_REPO_PATH):
    """Materializes everything new since the last materialize() call, up to end_date
    (defaults to now). This is what the dashboard/live-update path and the hourly
    feature pipeline use after appending a fresh observation, instead of
    re-materializing the entire history every time. SDK equivalent of
    `feast materialize-incremental <end>`, run in-process via fs.materialize_incremental()."""
    from feast import FeatureStore

    end_ts = pd.Timestamp(end_date, tz="UTC") if end_date is not None else pd.Timestamp.now(tz="UTC")

    fs = FeatureStore(repo_path=repo_path)
    try:
        fs.materialize_incremental(end_ts.to_pydatetime())
    except Exception as e:
        if "no such table" in str(e):
            raise FeastConfigError(
                f"Feast materialize-incremental failed because the online store has no table for "
                f"this FeatureView yet ({e}). Table creation happens during apply, not materialize - "
                f"run apply_feast_definitions() first (it's safe to re-run), then materialize again."
            )
        if "does not exist in project" in str(e):
            raise FeastConfigError(
                f"Feast materialize-incremental failed because the registry at {repo_path} doesn't "
                f"currently contain the expected entity/FeatureView/FeatureService ({e}). The "
                f"registry was likely reset or overwritten since it was last applied (a concurrent "
                f"process re-running apply() against the same repo_path, a git pull, a sync tool "
                f"restoring an older version, or multiple project copies on disk being run "
                f"interchangeably). Fix: run apply_feast_definitions() again, then retry."
            )
        raise FeastConfigError(f"Feast materialize-incremental failed ({e}).")

    print(f"Materialized (via SDK, incremental) up to {end_ts} into the online store.")
    return fs


def reset_feast_online_state(repo_path=FEAST_REPO_PATH):
    """Deletes the local Feast registry and online store (registry.db, online_store.db)
    so apply_feast_definitions()/materialize_*() can rebuild them from a clean slate.
    Does NOT touch the offline Parquet source (karachi_features.parquet) - your
    historical feature data is preserved; only Feast's own bookkeeping/online-serving
    state is reset.

    Use this if you ever see errors like "Feature view ... is in state 'MATERIALIZING'
    and cannot serve features" or "no such table: ..." - both mean Feast's local
    registry/online-store state got left inconsistent (typically: a materialize call
    was interrupted, or apply/materialize previously ran against a different Python/
    Feast installation than the one reading it now - see the module docstring's note
    on why apply_feast_definitions()/materialize_*() call the SDK directly rather than
    shelling out to the `feast` CLI). For a local, file-based Feast deployment, a clean
    re-apply + re-materialize is the supported recovery path - there's no "repair
    in place" for a corrupted SQLite/registry file.

    After calling this, run (in order): apply_feast_definitions() then
    materialize_feast_features(start, end) [or materialize_incremental()]."""
    data_dir = os.path.join(repo_path, "data")
    removed = []
    for fname in ["registry.db", "online_store.db"]:
        p = os.path.join(data_dir, fname)
        if os.path.exists(p):
            os.remove(p)
            removed.append(p)
    if removed:
        print(f"Removed: {removed}")
    else:
        print("Nothing to remove - no registry.db/online_store.db found at "
              f"{data_dir}.")
    print("Next steps: apply_feast_definitions(), then materialize_feast_features(start, end) "
          "or materialize_incremental().")
    return removed



def get_feature_store(repo_path=FEAST_REPO_PATH):
    from feast import FeatureStore
    if not os.path.exists(os.path.join(repo_path, "feature_store.yaml")):
        raise FeastConfigError(
            f"No feature_store.yaml found at {repo_path}. Run apply_feast_definitions() "
            f"(which requires the yaml + generated repo files) before using the store."
        )
    return FeatureStore(repo_path=repo_path)


def get_registered_feature_columns(feature_view_name=FEATURE_VIEW_NAME, repo_path=FEAST_REPO_PATH):
    """Returns the feature column names currently registered in Feast's applied
    FeatureView, introspected directly from the registry - NOT read from
    models/feature_columns.json. This is what lets the hourly feature pipeline run
    correctly even when no model has been trained yet in this environment (e.g. a
    fresh CI checkout): the source of truth for "what features does Feast expect" is
    the FeatureView that was actually applied, which is exactly the schema
    write_offline_source()/append_latest_observation_to_offline_source() must match.
    """
    fs = get_feature_store(repo_path)
    try:
        fv = fs.get_feature_view(feature_view_name)
    except Exception as e:
        raise FeastConfigError(
            f"FeatureView '{feature_view_name}' is not registered in {repo_path}. "
            f"Run apply_feast_definitions() (feast apply) at least once - typically as "
            f"part of the training pipeline / notebook - before running the feature "
            f"pipeline. Original error: {e}"
        )
    return [f.name for f in fv.schema if f.name != ENTITY_NAME]


def ingest_latest_observation(weather_df, air_df, create_features_fn, merge_datasets_fn,
                               feature_cols=None, repo_path=FEAST_REPO_PATH):
    """Single shared function for "get the freshest possible feature row into Feast,"
    used by BOTH dashboard/app.py (on-demand, when a user opens the dashboard) and
    scripts/feature_pipeline.py (the hourly GitHub Actions job) - this is what keeps
    the ingestion logic from having two drifting copies. Takes raw weather_df/air_df
    (as returned by data_pipeline.fetch_recent_weather_and_air_quality), merges and
    feature-engineers them with the EXACT SAME functions training used
    (merge_datasets_fn / create_features_fn - passed in rather than imported here, so
    this module doesn't need a hard dependency on data_pipeline.py/feature_engineering.py
    beyond what the caller already has), appends the latest complete row to Feast's
    offline source, and materializes it into the online store.

    Returns (observed_history_df, future_weather_df, latest_feature_row_df) so callers
    that also need to run a recursive forecast (the dashboard) can reuse the same fetch
    without a second Open-Meteo round-trip.
    """
    if feature_cols is None:
        feature_cols = get_registered_feature_columns(repo_path=repo_path)

    merged = merge_datasets_fn(weather_df, air_df)
    merged = merged.sort_values("timestamp").reset_index(drop=True)

    now_floor = pd.Timestamp.now().floor("h")
    observed = merged[merged["timestamp"] <= min(now_floor, merged["timestamp"].max())].copy()
    if len(observed) < 200:
        raise RuntimeError(
            f"Only {len(observed)} recent observed hours available - not enough to build "
            f"lag/rolling features (need >=200). Increase past_days in the Open-Meteo fetch."
        )

    featured = create_features_fn(observed)
    featured = featured.dropna(subset=[c for c in featured.columns if "lag_168" in c])
    if featured.empty:
        raise RuntimeError("Feature engineering produced no complete rows (insufficient history window).")

    latest_row = featured.tail(1)
    append_latest_observation_to_offline_source(latest_row, feature_cols, parquet_path=OFFLINE_PARQUET_PATH)
    materialize_incremental(end_date=latest_row["timestamp"].iloc[0] + pd.Timedelta(hours=1), repo_path=repo_path)

    future_weather = merged[merged["timestamp"] > observed["timestamp"].max()].copy()
    return observed, future_weather, latest_row



def load_training_features_from_feast(model_df, target_horizons=TARGET_HORIZONS,
                                       feature_service_name=FEATURE_SERVICE_NAME,
                                       repo_path=FEAST_REPO_PATH):
    """THE function that satisfies internship requirement #2: training data is
    retrieved from Feast's historical (offline) store, not read directly from a
    pandas DataFrame.

    We build an entity_df containing only the entity key, event_timestamp, and the
    TARGET columns (never feature columns - those come from Feast). Feast then joins
    its point-in-time-correct feature values onto each row of entity_df: for the row
    at event_timestamp T, Feast returns the feature values that were valid as of T
    (i.e. it will never attach a feature whose own event_timestamp is > T). That
    point-in-time join is exactly the mechanism that prevents future information
    leaking into a training example - it's enforced by Feast itself, not by us
    remembering to shift() something correctly a second time.
    """
    fs = get_feature_store(repo_path)
    feature_service = fs.get_feature_service(feature_service_name)

  
    passenger_cols = ["timestamp", "us_aqi"] + [f"AQI_t+{h}" for h in target_horizons]
    entity_df = model_df[passenger_cols].copy()
    entity_df[ENTITY_NAME] = ENTITY_VALUE
    entity_df["event_timestamp"] = pd.to_datetime(entity_df["timestamp"], utc=True)
    entity_df = entity_df.drop(columns=["timestamp"])

    print(f"Requesting historical features from Feast for {len(entity_df):,} entity rows "
          f"via feature service '{feature_service_name}'...")
    training_df = fs.get_historical_features(entity_df=entity_df, features=feature_service).to_df()

    training_df = training_df.rename(columns={"event_timestamp": "timestamp"})
    training_df["timestamp"] = pd.to_datetime(training_df["timestamp"]).dt.tz_localize(None)
    training_df = training_df.sort_values("timestamp").reset_index(drop=True)

    print(f"Retrieved {training_df.shape[0]:,} rows x {training_df.shape[1]} columns from Feast "
          f"(features + targets + entity/timestamp).")
    return training_df



def verify_feast_setup(feature_service_name=FEATURE_SERVICE_NAME, repo_path=FEAST_REPO_PATH):
    """Pre-flight diagnostic the dashboard calls BEFORE attempting online retrieval, so
    a missing/incomplete Feast setup produces one clear, actionable message instead of
    a raw sqlite3.OperationalError or Feast internals traceback surfacing in the UI.
    This does NOT catch-and-hide the eventual real error if setup looks fine but
    retrieval still fails for some other reason - it only front-loads the checks that
    have a well-known, specific fix.

    Returns a dict: {"ok": bool, "checks": {...}, "message": str}. Never raises - the
    caller (dashboard) decides how to present a non-ok result.
    """
    import sqlite3

    checks = {}
    data_dir = os.path.join(repo_path, "data")
    registry_path = os.path.join(data_dir, "registry.db")
    online_path = os.path.join(data_dir, "online_store.db")
    parquet_path = os.path.join(data_dir, "karachi_features.parquet")

    checks["feature_store_yaml_exists"] = os.path.exists(os.path.join(repo_path, "feature_store.yaml"))
    checks["feature_views_py_exists"] = os.path.exists(os.path.join(repo_path, "feature_views.py"))
    checks["feature_service_py_exists"] = os.path.exists(os.path.join(repo_path, "feature_service.py"))
    checks["offline_parquet_exists"] = os.path.exists(parquet_path)
    checks["registry_db_exists"] = os.path.exists(registry_path)
    checks["online_store_db_exists"] = os.path.exists(online_path)

    if not (checks["feature_store_yaml_exists"] and checks["feature_views_py_exists"]
            and checks["feature_service_py_exists"]):
        return {"ok": False, "checks": checks,
                "message": "Feast repo definitions are missing (feature_store.yaml / feature_views.py / "
                            "feature_service.py). Run the notebook through 'Register Feature Definitions' "
                            "at least once - this generates those files from your actual feature list."}

    if not checks["registry_db_exists"]:
        return {"ok": False, "checks": checks,
                "message": "Feast has never been applied in this checkout (no registry.db). "
                            "Run apply_feast_definitions() - or the notebook's 'Register Feature "
                            "Definitions' section - first."}

    if not checks["online_store_db_exists"]:
        return {"ok": False, "checks": checks,
                "message": "Feast's online store file doesn't exist yet (no online_store.db). "
                            "Run materialize_feast_features(start, end) - or the notebook's "
                            "'Materialize Features' section - to populate it."}

 
    fs = None
    try:
        fs = get_feature_store(repo_path)
        project_name = fs.config.project
    except Exception as e:
        return {"ok": False, "checks": checks,
                "message": f"Could not open the Feast feature store ({e})."}

    expected_table = f"{project_name}_{FEATURE_VIEW_NAME}"
    checks["expected_table_name"] = expected_table
    try:
        conn = sqlite3.connect(online_path)
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        conn.close()
    except Exception as e:
        return {"ok": False, "checks": checks, "message": f"Could not read {online_path}: {e}"}

    checks["online_table_exists"] = expected_table in tables
    if not checks["online_table_exists"]:
        return {"ok": False, "checks": checks,
                "message": f"The online store exists but has no table for this FeatureView "
                            f"(expected '{expected_table}', found {sorted(tables) or 'no tables'}). "
                            f"This usually means apply_feast_definitions() and "
                            f"materialize_feast_features() ran against DIFFERENT local Feast state at "
                            f"some point (e.g. before this project switched to calling the Feast SDK "
                            f"directly instead of the `feast` CLI - see feast_utils.py's module "
                            f"docstring). Fix: call reset_feast_online_state(), then "
                            f"apply_feast_definitions(), then materialize_feast_features(start, end)."}


    try:
        fv = fs.get_feature_view(FEATURE_VIEW_NAME)
        
        status = getattr(fv, "materialization_intervals", None)
        checks["feature_view_status_readable"] = True
    except Exception as e:
        checks["feature_view_status_readable"] = False
        checks["feature_view_status_error"] = str(e)

  
    from feast.errors import FeastObjectNotFoundException
    try:
        entity_rows = [{ENTITY_NAME: ENTITY_VALUE}]
        feature_service = fs.get_feature_service(feature_service_name)
        online_result = fs.get_online_features(features=feature_service, entity_rows=entity_rows)
        online_df = online_result.to_df()
        has_data = not (online_df.empty or online_df.drop(columns=[ENTITY_NAME], errors="ignore").isna().all(axis=None))
        checks["online_read_succeeded"] = True
        checks["online_read_has_data"] = has_data
        if not has_data:
            return {"ok": False, "checks": checks,
                    "message": "The online store table exists but has no data for this entity yet. "
                                "Run materialize_feast_features(start, end) to populate it."}
    except FeastObjectNotFoundException as e:
        return {"ok": False, "checks": checks,
                "message": f"The registry at {repo_path} does not currently contain the expected "
                            f"entity/FeatureView/FeatureService ({e}). It was likely reset or "
                            f"overwritten since it was last applied (a concurrent process re-running "
                            f"apply() against this same repo_path, a git pull, a sync tool restoring "
                            f"an older version, or multiple project copies on disk being run "
                            f"interchangeably). Fix: make sure only one process/session touches this "
                            f"repo_path at a time, then call apply_feast_definitions() followed by "
                            f"materialize_feast_features(start, end)."}
    except ValueError as e:
        if "MATERIALIZING" in str(e):
            return {"ok": False, "checks": checks,
                    "message": f"FeatureView '{FEATURE_VIEW_NAME}' is stuck in state 'MATERIALIZING' "
                                f"(a previous materialize call was likely interrupted before finishing). "
                                f"Fix: call reset_feast_online_state(), then apply_feast_definitions(), "
                                f"then materialize_feast_features(start, end)."}
        return {"ok": False, "checks": checks, "message": f"Online read failed: {e}"}
    except Exception as e:
        checks["online_read_succeeded"] = False
        return {"ok": False, "checks": checks,
                "message": f"Online read failed unexpectedly: {type(e).__name__}: {e}"}

    return {"ok": True, "checks": checks, "message": "Feast online store is set up correctly."}


def bootstrap_materialize_if_needed(feature_service_name=FEATURE_SERVICE_NAME, repo_path=FEAST_REPO_PATH):
    """Self-heals the single most common "everything is applied correctly but the
    online store is simply empty" state - table exists (apply() ran fine), but
    materialize() has never actually been run, so verify_feast_setup() reports
    online_table_exists=True / online_read_has_data=False. Rather than requiring the
    user to look up their own data's date range and call materialize_feast_features()
    by hand every time this happens (a fresh checkout, a reset_feast_online_state()
    call that wasn't followed all the way through, etc.), this reads the actual
    min/max event_timestamp straight out of the offline Parquet source and
    materializes exactly that range - which is always the right range to ask for,
    since it's this project's actual data.

    Does NOT attempt to fix anything else (missing table, stuck MATERIALIZING state,
    missing registry entries, etc.) - those need a real reset_feast_online_state() +
    apply_feast_definitions() cycle, which is a deliberate, visible action a caller
    should take knowingly rather than something this function silently does on their
    behalf. This only ever fills in *missing data* for an otherwise-healthy store.

    Returns (attempted: bool, result: dict) where `result` is the verify_feast_setup()
    output after the attempt (or the original check if nothing was attempted)."""
    check = verify_feast_setup(feature_service_name=feature_service_name, repo_path=repo_path)
    if check["ok"]:
        return False, check

    checks = check["checks"]
    needs_bootstrap = checks.get("online_table_exists") is True and checks.get("online_read_has_data") is False
    if not needs_bootstrap:
        
        return False, check

    parquet_path = os.path.join(repo_path, "data", "karachi_features.parquet")
    if not os.path.exists(parquet_path):
        return False, {"ok": False, "checks": checks,
                        "message": f"Cannot auto-materialize: offline source {parquet_path} doesn't exist."}

    df = pd.read_parquet(parquet_path, columns=["event_timestamp"])
    if df.empty:
        return False, {"ok": False, "checks": checks,
                        "message": f"Cannot auto-materialize: offline source {parquet_path} has no rows."}

    start_date, end_date = df["event_timestamp"].min(), df["event_timestamp"].max()
    print(f"bootstrap_materialize_if_needed: online store has no data yet - materializing the full "
          f"offline range ({start_date} to {end_date}) automatically...")
    materialize_feast_features(start_date, end_date, repo_path=repo_path)

    return True, verify_feast_setup(feature_service_name=feature_service_name, repo_path=repo_path)


def get_latest_features_from_feast(feature_service_name=FEATURE_SERVICE_NAME, repo_path=FEAST_REPO_PATH):
    """THE function that satisfies internship requirement #3: the dashboard retrieves
    its current feature vector from Feast's ONLINE store (a fast key-value lookup),
    not by reading processed_df.iloc[-1] directly. Requires that
    materialize()/materialize_incremental() has been run at least once so the online
    store actually has a value for our entity.

    Deliberately does NOT catch-and-hide sqlite/Feast errors: if the online store is
    missing its table, a FeatureView is stuck mid-materialization, or the registry is
    missing the entity/feature service entirely (e.g. it was reset/overwritten by a
    concurrent process - a separate notebook/terminal re-running apply() against the
    same repo_path while this process was already running, a git pull replacing local
    files, a sync tool restoring an older version, etc.), this re-raises EVERY such
    condition as a FeastConfigError with an actionable message (see
    verify_feast_setup() for the same diagnosis, callable up-front) rather than
    letting a raw Feast/sqlite exception reach the caller - per the explicit
    requirement that a Feast problem must surface as a clear Feast problem, not be
    hidden behind a bare except, and not crash the caller with an unhandled traceback
    either."""
    import sqlite3
    from feast.errors import FeastObjectNotFoundException

    fs = get_feature_store(repo_path)

    try:
        feature_service = fs.get_feature_service(feature_service_name)
        entity_rows = [{ENTITY_NAME: ENTITY_VALUE}]
        online_result = fs.get_online_features(features=feature_service, entity_rows=entity_rows)
    except FeastObjectNotFoundException as e:
        raise FeastConfigError(
            f"Feast's registry at {repo_path} does not currently contain the entity/FeatureService "
            f"this project expects ({e}). This means the registry was reset or overwritten by "
            f"something else since it was last applied - most commonly: a second notebook/terminal "
            f"session re-running apply_feast_definitions() against the same repo_path concurrently, "
            f"a `git pull` replacing local feature_store/data/ files, a sync tool (OneDrive/Dropbox) "
            f"restoring an older version, or multiple copies of this project on disk being run "
            f"interchangeably. Fix: make sure only ONE process/session touches this repo_path at a "
            f"time, then run apply_feast_definitions() followed by materialize_feast_features(start, "
            f"end) (or materialize_incremental()) again. Call verify_feast_setup() for a full "
            f"diagnostic, including which repo_path is actually being read."
        ) from e
    except ValueError as e:
        if "MATERIALIZING" in str(e):
            raise FeastConfigError(
                f"FeatureView '{FEATURE_VIEW_NAME}' is stuck in state 'MATERIALIZING' (a previous "
                f"materialize call was likely interrupted). Fix: reset_feast_online_state() then "
                f"apply_feast_definitions() then materialize_feast_features(start, end)."
            ) from e
        raise FeastConfigError(f"Feast online retrieval failed: {e}") from e
    except sqlite3.OperationalError as e:
       
        if "no such table" in str(e):
            raise FeastConfigError(
                f"Feast's online store is missing the expected table ({e}). This means "
                f"apply_feast_definitions() + materialize_feast_features() haven't successfully run "
                f"against the online store this process is reading, or a previous run left it in an "
                f"inconsistent state. Fix: reset_feast_online_state() then apply_feast_definitions() "
                f"then materialize_feast_features(start, end). Call verify_feast_setup() for a full "
                f"diagnostic."
            ) from e
        raise FeastConfigError(f"Feast online retrieval failed (sqlite error): {e}") from e
    except Exception as e:
        
        raise FeastConfigError(
            f"Feast online retrieval failed unexpectedly ({type(e).__name__}: {e}). Call "
            f"verify_feast_setup() for a full diagnostic, or reset_feast_online_state() + "
            f"apply_feast_definitions() + materialize_feast_features(start, end) to rebuild from "
            f"a clean slate."
        ) from e

    online_df = online_result.to_df()

    if online_df.empty or online_df.drop(columns=[ENTITY_NAME], errors="ignore").isna().all(axis=None):
        raise FeastConfigError(
            "Feast online store returned no feature values for this entity. "
            "Have you run materialize() / materialize_incremental() at least once "
            "since writing new data to the offline source?"
        )
    return online_df


def get_online_features_for_prediction(feature_cols, feature_service_name=FEATURE_SERVICE_NAME,
                                        repo_path=FEAST_REPO_PATH):
    """Returns a single-row pandas DataFrame of features, in the exact `feature_cols`
    order the model was trained on, pulled from Feast's online store. This is what the
    dashboard's forecasting step calls immediately before invoking the trained model -
    it never falls back to reading the processed DataFrame/CSV directly."""
    online_df = get_latest_features_from_feast(feature_service_name, repo_path)
    missing = [c for c in feature_cols if c not in online_df.columns]
    if missing:
        raise FeastConfigError(
            f"{len(missing)} feature(s) expected by the model are missing from the Feast online "
            f"response (e.g. {missing[:5]}). This usually means the FeatureView schema and the "
            f"model's saved feature_columns.json have drifted apart - re-run "
            f"generate_feature_views_file() + apply_feast_definitions() + materialize."
        )
    return online_df[feature_cols].reset_index(drop=True)


def check_training_vs_online_schema(training_feature_cols, online_df):
    online_cols = [c for c in online_df.columns if c not in (ENTITY_NAME, "event_timestamp")]
    missing_online = sorted(set(training_feature_cols) - set(online_cols))
    unexpected_online = sorted(set(online_cols) - set(training_feature_cols))
    same_order = [c for c in training_feature_cols if c in online_cols] == \
                 [c for c in online_cols if c in training_feature_cols]

    report = {
        "n_training_features": len(training_feature_cols),
        "n_online_features": len(online_cols),
        "missing_from_online": missing_online,
        "unexpected_in_online": unexpected_online,
        "same_relative_order": same_order,
        "schemas_match": (len(missing_online) == 0 and len(unexpected_online) == 0),
    }
    return report
