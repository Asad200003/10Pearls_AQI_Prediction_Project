def _feast_dtype_name(pandas_dtype):
    """Map a pandas dtype to the Feast primitive type name used in the generated
    feature_views.py (kept as a string here; the actual feast.types objects are
    constructed inside the generated file, imported fresh at apply-time)."""
    kind = pandas_dtype.kind
    if kind == "f":
        return "Float32"
    elif kind in ("i", "u"):
        return "Int64"
    elif kind == "b":
        return "Bool"
    else:
        return "String"



def write_offline_source(model_df, feature_cols, parquet_path=OFFLINE_PARQUET_PATH):
    """Write the processed, feature-engineered DataFrame to the Parquet file Feast's
    offline store reads from. Only feature columns + entity + timestamps are written -
    target (AQI_t+h) columns are intentionally excluded from this file so they can
    never be pulled in as a Feast *feature* by accident (see module docstring)."""
    out = model_df[["timestamp"] + feature_cols].copy()
    out[ENTITY_NAME] = ENTITY_VALUE
    out["event_timestamp"] = pd.to_datetime(out["timestamp"], utc=True)
    out["created_timestamp"] = pd.Timestamp.now(tz="UTC")
    out = out.drop(columns=["timestamp"])

  
    for c in feature_cols:
        if out[c].dtype.kind in ("i", "u", "f"):
            out[c] = out[c].astype("float32")

    out.to_parquet(parquet_path, index=False)
    print(f"Wrote {len(out):,} rows x {len(feature_cols)} features to Feast offline source:")
    print(f"  {parquet_path}")
    return parquet_path


def append_latest_observation_to_offline_source(new_feature_row_df, feature_cols,
                                                  parquet_path=OFFLINE_PARQUET_PATH):
    """Append a freshly-computed live feature row (from the dashboard's own
    fetch -> create_features() pass) to the same offline Parquet source, so a single
    materialize-incremental call can push it straight into the online store. This is
    what keeps "the pipeline that feeds Feast" identical for both training-time
    (historical backfill) and serving-time (live update)."""
    row = new_feature_row_df[["timestamp"] + feature_cols].copy()
    row[ENTITY_NAME] = ENTITY_VALUE
    row["event_timestamp"] = pd.to_datetime(row["timestamp"], utc=True)
    row["created_timestamp"] = pd.Timestamp.now(tz="UTC")
    row = row.drop(columns=["timestamp"])
    for c in feature_cols:
        if row[c].dtype.kind in ("i", "u", "f"):
            row[c] = row[c].astype("float32")

    if os.path.exists(parquet_path):
        existing = pd.read_parquet(parquet_path)
        combined = pd.concat([existing, row], ignore_index=True)
        combined = combined.drop_duplicates(subset=["event_timestamp", ENTITY_NAME], keep="last")
        combined = combined.sort_values("event_timestamp").reset_index(drop=True)
    else:
        combined = row

    combined.to_parquet(parquet_path, index=False)
    return parquet_path



